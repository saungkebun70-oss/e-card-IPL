select
  d.blok_rumah,
  d.nama_warga,
  d.no_wa,
  d.status_hunian,
  d.nominal_iuran,
  d.pin_akses,
  'warga',
  true
from data_warga d
where not exists (
  select 1
  from public.users_warga u
  where regexp_replace(upper(trim(u.blok_rumah)), '^([A-Z]+)0*([0-9]+)/0*([0-9]+)$', '\1\2/\3')
      = regexp_replace(upper(trim(d.blok_rumah)), '^([A-Z]+)0*([0-9]+)/0*([0-9]+)$', '\1\2/\3')
)
on conflict (blok_rumah) do nothing;
